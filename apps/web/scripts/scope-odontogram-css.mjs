#!/usr/bin/env node
/**
 * Adapts react-advanced-odontogram's global stylesheet so it can live inside
 * the DaliDoc app without leaking into it.
 *
 * The package ships one unlayered, global stylesheet (`dist/style.css`). Used
 * as-is it would:
 *   1. redefine `--bg`, `--card`, `--muted`, `--accent`, `--line`, `--text`,
 *      `--panel` and `--accent2` on `:root` — names DaliDoc's own design
 *      tokens use with different meanings;
 *   2. restyle `html`, `body`, `*` and every `<select>` in the app;
 *   3. beat every Tailwind utility, because unlayered CSS wins over layers.
 *
 * This script rewrites it at install/build time:
 *   - the eight internal variables become `--rao-*` (the engine's JavaScript
 *     only ever reads the public `--odon-*` variables, so this is invisible to
 *     it);
 *   - `html` / `body` / `*` rules are dropped; `select` and the `!important`
 *     `.hidden` rule are scoped to the odontogram's own containers;
 *   - the hard-coded blue/green accents become `color-mix()` over the themed
 *     accent variables, so the chart follows DaliDoc's brand and dark mode;
 *   - everything is wrapped in `@layer odontogram`, which globals.css orders
 *     after Tailwind's base layer and before its utilities.
 *
 * Output: src/styles/vendor/odontogram.css (git-ignored, regenerated by the
 * postinstall / predev / prebuild hooks).
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const here = dirname(fileURLToPath(import.meta.url));
// The package only exports its ESM entry and `./style.css`, so locate dist/
// through the entry point rather than through package.json.
const distDir = dirname(fileURLToPath(import.meta.resolve("react-advanced-odontogram")));
const pkgJson = JSON.parse(readFileSync(resolve(distDir, "../package.json"), "utf8"));
const source = resolve(distDir, "style.css");
const target = resolve(here, "../src/styles/vendor/odontogram.css");

const INTERNAL_VARS = ["accent2", "accent", "panel", "card", "muted", "text", "line", "bg"];
const SELECT_SCOPE = ':where(.odontogram-root, .perio-overlay, [class*="odon-"])';

/** Accent colours hard-coded in the stylesheet → the themed variable they stand for. */
const ACCENT_FAMILIES = [
  { hex: ["3b7bff", "3b82f6", "60a5fa", "640feb"], rgb: ["59,123,255", "96,165,250"], token: "var(--rao-accent)" },
  { hex: ["12b981"], rgb: ["18,185,129"], token: "var(--rao-accent2)" },
];

function renameInternalVars(value) {
  let out = value;
  for (const name of INTERNAL_VARS) {
    out = out.replace(new RegExp(`var\\(--${name}(?=[,)\\s])`, "g"), `var(--rao-${name}`);
  }
  return out;
}

function pct(alpha) {
  return `${Math.round(alpha * 1000) / 10}%`;
}

function themeAccents(value) {
  let out = value;
  for (const family of ACCENT_FAMILIES) {
    for (const hex of family.hex) {
      out = out.replace(new RegExp(`#${hex}([0-9a-f]{2})?\\b`, "gi"), (_m, a) =>
        a ? `color-mix(in srgb, ${family.token} ${pct(parseInt(a, 16) / 255)}, transparent)` : family.token,
      );
    }
    for (const rgb of family.rgb) {
      out = out.replace(new RegExp(`rgba\\(${rgb.replace(/,/g, "\\s*,\\s*")}\\s*,\\s*([0-9.]+)\\)`, "g"), (_m, a) =>
        `color-mix(in srgb, ${family.token} ${pct(Number(a))}, transparent)`,
      );
    }
  }
  return out;
}

const DROP = /^(?:\*|html|body|html\s*,\s*body|\.dark\s+body)$/;

function scopeSelector(selector) {
  const s = selector.trim();
  if (DROP.test(s)) return null;
  if (/^select\b/.test(s)) return `${SELECT_SCOPE} ${s}`;
  // `.hidden{display:none!important}` would beat Tailwind's responsive display
  // utilities everywhere in the app; keep it to the engine's own elements.
  if (s === ".hidden") return `${SELECT_SCOPE} .hidden, .perio-overlay.hidden, [class*="odon-"].hidden`;
  return s;
}

const root = postcss.parse(readFileSync(source, "utf8"), { from: source });

root.walkDecls((decl) => {
  const m = /^--(accent2|accent|panel|card|muted|text|line|bg)$/.exec(decl.prop);
  if (m) {
    // The variable definitions keep the library's own fallbacks: themeing
    // them here would make `--rao-accent` refer to itself.
    decl.prop = `--rao-${m[1]}`;
    decl.value = renameInternalVars(decl.value);
    return;
  }
  decl.value = themeAccents(renameInternalVars(decl.value));
});

root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  const kept = rule.selectors.map(scopeSelector).filter(Boolean);
  if (kept.length === 0) rule.remove();
  else rule.selectors = kept;
});

const layer = postcss.atRule({ name: "layer", params: "odontogram" });
layer.append(root.nodes);

const banner =
  `/*! Generated by scripts/scope-odontogram-css.mjs from react-advanced-odontogram@${pkgJson.version} ` +
  `dist/style.css — do not edit.\n` +
  ` *  React Advanced Odontogram © 2025-2026 Zoltán Dul, MIT License. */\n`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, banner + layer.toString() + "\n");
console.log(`odontogram css → ${target.replace(resolve(here, ".."), ".")}`);
