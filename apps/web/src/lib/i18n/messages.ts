const MESSAGES: Record<Locale, Messages> = { fr, en, ar };

const pluralRules = new Map<Locale, Intl.PluralRules>();
function plural(locale: Locale, n: number): "one" | "other" {
  let rules = pluralRules.get(locale);
  if (!rules) {
    rules = new Intl.PluralRules(locale);
    pluralRules.set(locale, rules);
  }
  return rules.select(n) === "one" ? "one" : "other";
}

export function translate(locale: Locale, key: MessageKey, vars?: MessageVars): string {
  const template = MESSAGES[locale][key] ?? fr[key];
  if (!vars) return template;
  return template
    .replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_m, name: string, one: string, other: string) =>
      plural(locale, Number(vars[name] ?? 0)) === "one" ? one : other,
    )
    .replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
